using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using KiHan.UI;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace KiHan.Editor
{
    /// <summary>
    /// UI 自动绑定 (@ 前缀)：
    /// - 扫描 UI 预制体目录下每个 UIPanel / UIView 组件作用域内名字以 @ 开头的节点 (不深入带 UIPanel / UIView 的子节点)
    /// - 每个类生成 &lt;类名&gt;.Bind.cs (partial 类的 [SerializeField] 字段)，编译后把节点赋给对应字段
    /// 命名：@StartBtn → _startBtn；@Name:Type 指定类型 (GameObject 或组件类名)；@Item_0 / @Item_1 合并为数组 _item
    /// 规则详见 DOCS/UI_FRAMEWORK.md 第 5 节
    /// </summary>
    public static class UIBindGenerator
    {
        public const string PrefabRoot = "Assets/AssetPackages/Resources/UI";
        private const string PendingKey = "KiHan.UIBind.PendingAssign";

        /// <summary>
        /// 未指定类型时的推断顺序 (节点上第一个匹配的组件)；UIView 子类优先
        /// </summary>
        private static readonly Type[] InferOrder =
        {
            typeof(UnityEngine.UI.Button),
            typeof(UnityEngine.UI.Toggle),
            typeof(UnityEngine.UI.Slider),
            typeof(TMPro.TMP_InputField),
            typeof(UnityEngine.UI.ScrollRect),
            typeof(TMPro.TMP_Text),
            typeof(UnityEngine.UI.RawImage),
            typeof(UnityEngine.UI.Image),
            typeof(RectTransform),
        };

        /// <summary>
        /// 一个 @ 节点
        /// </summary>
        private sealed class Node
        {
            public string Field;
            public int Index = -1;
            public Type Type;
            public Object Target;
            public string Error;
        }

        /// <summary>
        /// 一个类的字段 (按首次出现顺序)
        /// </summary>
        private sealed class ClassFields
        {
            public Type Owner;
            public string Prefab;
            public readonly List<(string field, Type type, bool array)> Fields = new List<(string, Type, bool)>();
        }

        #region 菜单

        [MenuItem("KiHan/UI/生成全部绑定")]
        private static void GenerateAllMenu()
        {
            List<string> problems = GenerateAll();
            foreach (string p in problems) Debug.LogError($"[UIBind] {p}");
            if (problems.Count == 0) Debug.Log("[UIBind] 生成完成");
        }

        [MenuItem("KiHan/UI/校验全部面板")]
        private static void ValidateMenu()
        {
            List<string> problems = Validate();
            foreach (string p in problems) Debug.LogError($"[UIBind] {p}");
            if (problems.Count == 0) Debug.Log("[UIBind] 校验通过");
        }

        #endregion

        #region 生成

        /// <summary>
        /// 生成全部 .Bind.cs；有文件变化时等编译完成后自动赋值，否则立即赋值。返回问题列表
        /// </summary>
        public static List<string> GenerateAll()
        {
            var problems = new List<string>();
            Dictionary<Type, ClassFields> classes = Collect(problems);
            bool changed = false;
            foreach (ClassFields cls in classes.Values)
            {
                string path = BindFilePath(cls.Owner, problems);
                if (path == null) continue;
                if (cls.Fields.Count == 0)
                {
                    // 没有 @ 节点的类不需要绑定文件 (类本身也不必声明 partial)
                    if (File.Exists(path) && AssetDatabase.DeleteAsset(path)) changed = true;
                    continue;
                }
                string text = Render(cls);
                if (File.Exists(path) && File.ReadAllText(path) == text) continue;
                File.WriteAllText(path, text, new UTF8Encoding(false));
                changed = true;
                Debug.Log($"[UIBind] 生成 {path}");
            }

            if (changed)
            {
                SessionState.SetBool(PendingKey, true);
                AssetDatabase.Refresh();
            }
            else
            {
                problems.AddRange(AssignAll());
            }
            return problems;
        }

        [InitializeOnLoadMethod]
        private static void AssignPending()
        {
            if (!SessionState.GetBool(PendingKey, false)) return;
            SessionState.SetBool(PendingKey, false);
            EditorApplication.delayCall += () =>
            {
                foreach (string p in AssignAll()) Debug.LogError($"[UIBind] {p}");
                Debug.Log("[UIBind] 绑定赋值完成");
            };
        }

        private static string Render(ClassFields cls)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append($"// 由 KiHan/UI/生成绑定 根据预制体 {cls.Prefab} 的 @ 节点生成，请勿手动修改\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("using UnityEngine;\n\n");
            string ns = cls.Owner.Namespace;
            string indent = string.IsNullOrEmpty(ns) ? string.Empty : "    ";
            if (!string.IsNullOrEmpty(ns)) sb.Append($"namespace {ns}\n{{\n");
            sb.Append($"{indent}public partial class {cls.Owner.Name}\n{indent}{{\n");
            foreach ((string field, Type type, bool array) in cls.Fields)
            {
                sb.Append($"{indent}    [SerializeField] private {TypeName(type)}{(array ? "[]" : string.Empty)} {field};\n");
            }
            sb.Append($"{indent}}}\n");
            if (!string.IsNullOrEmpty(ns)) sb.Append("}\n");
            return sb.ToString();
        }

        private static string TypeName(Type type) => "global::" + type.FullName.Replace('+', '.');

        private static string BindFilePath(Type owner, List<string> problems)
        {
            foreach (string guid in AssetDatabase.FindAssets($"t:MonoScript {owner.Name}"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                var script = AssetDatabase.LoadAssetAtPath<MonoScript>(path);
                if (script != null && script.GetClass() == owner) return Path.Combine(Path.GetDirectoryName(path), owner.Name + ".Bind.cs").Replace('\\', '/');
            }
            problems.Add($"找不到类 {owner.FullName} 的脚本文件 (文件名需与类名一致)");
            return null;
        }

        #endregion

        #region 收集

        private static IEnumerable<string> UIPrefabs() =>
            AssetDatabase.FindAssets("t:Prefab", new[] { PrefabRoot }).Select(AssetDatabase.GUIDToAssetPath).OrderBy(p => p, StringComparer.Ordinal);

        private static bool IsOwner(Component c) => c is UIPanel || c is UIView;

        /// <summary>
        /// 组件是否属于嵌套预制体实例 (由其源预制体负责绑定)
        /// </summary>
        private static bool IsNested(Component c, GameObject prefabRoot)
        {
            GameObject instanceRoot = PrefabUtility.GetNearestPrefabInstanceRoot(c.gameObject);
            return instanceRoot != null && instanceRoot != prefabRoot;
        }

        private static Dictionary<Type, ClassFields> Collect(List<string> problems)
        {
            var classes = new Dictionary<Type, ClassFields>();
            foreach (string path in UIPrefabs())
            {
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (prefab == null) continue;
                foreach (Component owner in prefab.GetComponentsInChildren<Component>(true))
                {
                    if (owner == null || !IsOwner(owner) || IsNested(owner, prefab)) continue;
                    List<Node> nodes = Scan(owner, problems, path);
                    if (!classes.TryGetValue(owner.GetType(), out ClassFields cls))
                    {
                        cls = new ClassFields { Owner = owner.GetType(), Prefab = path };
                        classes[owner.GetType()] = cls;
                    }
                    foreach (Node n in nodes)
                    {
                        if (n.Error != null) continue;
                        int i = cls.Fields.FindIndex(f => f.field == n.Field);
                        if (i < 0)
                        {
                            cls.Fields.Add((n.Field, n.Type, n.Index >= 0));
                        }
                        else if (cls.Fields[i].type != n.Type || cls.Fields[i].array != (n.Index >= 0))
                        {
                            problems.Add($"{path}: {owner.GetType().Name}.{n.Field} 的类型与其他预制体不一致 ({TypeName(cls.Fields[i].type)} / {TypeName(n.Type)})");
                        }
                    }
                }
            }
            return classes;
        }

        /// <summary>
        /// 扫描组件作用域内的 @ 节点 (不深入带 UIPanel / UIView 的子节点，但节点本身可绑定)
        /// </summary>
        private static List<Node> Scan(Component owner, List<string> problems, string prefabPath)
        {
            var nodes = new List<Node>();
            var seen = new HashSet<string>();
            Walk(owner.transform, true);

            void Walk(Transform t, bool isOwner)
            {
                foreach (Transform child in t)
                {
                    if (child.name.StartsWith("@", StringComparison.Ordinal))
                    {
                        Node n = Parse(child.gameObject);
                        if (n.Error != null)
                        {
                            problems.Add($"{prefabPath}: {owner.GetType().Name} 的节点 {child.name}: {n.Error}");
                        }
                        else if (!seen.Add(n.Index >= 0 ? $"{n.Field}#{n.Index}" : n.Field))
                        {
                            problems.Add($"{prefabPath}: {owner.GetType().Name} 内有重名的 @ 节点 {child.name}");
                        }
                        else
                        {
                            nodes.Add(n);
                        }
                    }
                    bool boundary = child.GetComponents<Component>().Any(c => c != null && IsOwner(c));
                    if (!boundary) Walk(child, false);
                }
            }
            return nodes;
        }

        private static Node Parse(GameObject go)
        {
            string name = go.name.Substring(1);
            string typeName = null;
            int colon = name.IndexOf(':');
            if (colon >= 0)
            {
                typeName = name.Substring(colon + 1).Trim();
                name = name.Substring(0, colon).Trim();
            }

            var n = new Node();
            int underscore = name.LastIndexOf('_');
            if (underscore > 0 && int.TryParse(name.Substring(underscore + 1), out int index))
            {
                n.Index = index;
                name = name.Substring(0, underscore);
            }
            if (name.Length == 0 || !(char.IsLetter(name[0]) || name[0] == '_') || !name.All(ch => char.IsLetterOrDigit(ch) || ch == '_'))
            {
                n.Error = "名字只能包含字母、数字与下划线";
                return n;
            }
            n.Field = "_" + char.ToLowerInvariant(name[0]) + name.Substring(1);

            if (typeName == null)
            {
                Component view = go.GetComponents<Component>().FirstOrDefault(c => c != null && IsOwner(c));
                if (view != null)
                {
                    n.Type = view.GetType();
                    n.Target = view;
                    return n;
                }
                foreach (Type t in InferOrder)
                {
                    Component c = go.GetComponent(t);
                    if (c == null) continue;
                    n.Type = t;
                    n.Target = c;
                    return n;
                }
                n.Error = "无法推断类型";
                return n;
            }

            if (typeName == "GameObject")
            {
                n.Type = typeof(GameObject);
                n.Target = go;
                return n;
            }
            Component match = go.GetComponents<Component>().FirstOrDefault(c => c != null && (c.GetType().Name == typeName || c.GetType().FullName == typeName));
            if (match == null)
            {
                n.Error = $"节点上没有组件 {typeName}";
                return n;
            }
            n.Type = match.GetType();
            n.Target = match;
            return n;
        }

        #endregion

        #region 赋值与校验

        /// <summary>
        /// 把全部 UI 预制体中的 @ 节点赋给对应字段 (只修改有变化的预制体)，返回问题列表
        /// </summary>
        public static List<string> AssignAll()
        {
            var problems = new List<string>();
            foreach (string path in UIPrefabs())
            {
                GameObject root = PrefabUtility.LoadPrefabContents(path);
                try
                {
                    bool dirty = false;
                    foreach (Component owner in root.GetComponentsInChildren<Component>(true))
                    {
                        if (owner == null || !IsOwner(owner) || IsNested(owner, root)) continue;
                        dirty |= Assign(owner, Scan(owner, problems, path), problems, path);
                    }
                    if (dirty) PrefabUtility.SaveAsPrefabAsset(root, path);
                }
                finally
                {
                    PrefabUtility.UnloadPrefabContents(root);
                }
            }
            return problems;
        }

        private static bool Assign(Component owner, List<Node> nodes, List<string> problems, string path)
        {
            var so = new SerializedObject(owner);
            foreach (IGrouping<string, Node> group in nodes.Where(n => n.Error == null).GroupBy(n => n.Field))
            {
                SerializedProperty prop = so.FindProperty(group.Key);
                if (prop == null)
                {
                    problems.Add($"{path}: {owner.GetType().Name} 没有字段 {group.Key} (先执行 KiHan/UI/生成全部绑定)");
                    continue;
                }
                if (prop.isArray && prop.propertyType == SerializedPropertyType.Generic)
                {
                    List<Node> items = group.OrderBy(n => n.Index).ToList();
                    for (int i = 0; i < items.Count; i++)
                    {
                        if (items[i].Index != i) problems.Add($"{path}: {owner.GetType().Name}.{group.Key} 数组下标不连续 (缺少 _{i})");
                    }
                    prop.arraySize = items.Count;
                    for (int i = 0; i < items.Count; i++) prop.GetArrayElementAtIndex(i).objectReferenceValue = items[i].Target;
                }
                else
                {
                    prop.objectReferenceValue = group.First().Target;
                }
            }
            return so.ApplyModifiedPropertiesWithoutUndo();
        }

        /// <summary>
        /// 校验：面板预制体位置与根节点脚本、@ 字段全部已赋值、绑定文件与预制体一致
        /// </summary>
        public static List<string> Validate()
        {
            var problems = new List<string>();

            foreach (Type type in TypeCache.GetTypesDerivedFrom<UIPanel>())
            {
                if (type.IsAbstract) continue;
                var meta = (UIPanelAttribute)Attribute.GetCustomAttribute(type, typeof(UIPanelAttribute));
                if (meta == null)
                {
                    problems.Add($"面板 {type.Name} 缺少 UIPanelAttribute");
                    continue;
                }
                string path = $"Assets/AssetPackages/Resources/{meta.Path}.prefab";
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (prefab == null) problems.Add($"面板 {type.Name} 的预制体不存在: {path}");
                else if (prefab.GetComponent(type) == null) problems.Add($"{path} 根节点没有挂 {type.Name}");
                else if (Path.GetFileNameWithoutExtension(path) != type.Name) problems.Add($"{path} 文件名与类名 {type.Name} 不一致");
            }

            Dictionary<Type, ClassFields> classes = Collect(problems);
            foreach (ClassFields cls in classes.Values)
            {
                string bindPath = BindFilePath(cls.Owner, problems);
                if (bindPath == null) continue;
                bool stale = cls.Fields.Count == 0 ? File.Exists(bindPath) : !File.Exists(bindPath) || File.ReadAllText(bindPath) != Render(cls);
                if (stale) problems.Add($"{bindPath} 与预制体的 @ 节点不一致，执行 KiHan/UI/生成全部绑定");
            }

            foreach (string path in UIPrefabs())
            {
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (prefab == null) continue;
                foreach (Component owner in prefab.GetComponentsInChildren<Component>(true))
                {
                    if (owner == null || !IsOwner(owner) || IsNested(owner, prefab)) continue;
                    var so = new SerializedObject(owner);
                    foreach (Node n in Scan(owner, problems, path))
                    {
                        if (n.Error != null) continue;
                        SerializedProperty prop = so.FindProperty(n.Field);
                        if (prop == null) continue; // 已在上面报告绑定文件不一致
                        bool assigned = prop.isArray && prop.propertyType == SerializedPropertyType.Generic
                            ? n.Index < prop.arraySize && prop.GetArrayElementAtIndex(n.Index).objectReferenceValue == n.Target
                            : prop.objectReferenceValue == n.Target;
                        if (!assigned) problems.Add($"{path}: {owner.GetType().Name}.{n.Field} 未赋值为节点 @{n.Field.Substring(1)}，执行 KiHan/UI/生成全部绑定");
                    }
                }
            }
            return problems;
        }

        #endregion
    }
}
